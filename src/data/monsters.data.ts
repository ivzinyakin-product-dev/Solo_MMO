import { MonsterDef, MonsterRank } from '../types/game.types';

function makeStats(level: number, rank: MonsterRank = 'NORMAL') {
  const baseHp = Math.max(45, Math.floor(45 * Math.pow(level, 1.55)));
  const baseAtk = Math.max(9, Math.floor(8 + level * 3.8 + Math.pow(level / 10, 2) * 6));
  const baseDef = Math.max(2, Math.floor(level * 1.6));
  // Классический RO (Патч 3.5): MonsterBaseEXP(L) = floor(11 * L^1.28), MonsterJobEXP(L) = floor(8 * L^1.28)
  const baseExp = Math.max(10, Math.floor(11 * Math.pow(level, 1.28)));
  const jobExp = Math.max(6, Math.floor(8 * Math.pow(level, 1.28)));
  const flee = Math.floor(5 + level * 1.5);
  const hit = Math.floor(175 + level * 2);

  if (rank === 'MVP') {
    return {
      hp: Math.round(baseHp * 5.0),
      atk: Math.round(baseAtk * 1.4),
      def: baseDef + 15,
      baseExp: Math.round(baseExp * 10),
      jobExp: Math.round(jobExp * 10),
      flee: flee + 10,
      hit: hit + 15,
    };
  }

  if (rank === 'ELITE') {
    return {
      hp: Math.round(baseHp * 2.5),
      atk: Math.round(baseAtk * 1.2),
      def: baseDef + 8,
      baseExp: Math.round(baseExp * 4),
      jobExp: Math.round(jobExp * 4),
      flee: flee + 5,
      hit: hit + 8,
    };
  }

  return { hp: baseHp, atk: baseAtk, def: baseDef, baseExp, jobExp, flee, hit };
}

